"""
generate_feed.py (версия 2 — работает с РЕАЛЬНЫМИ данными)

В отличие от первой версии, этот скрипт НЕ выдумывает объявления заново.
Он открывает уже существующий файл BaronNeon_feed.xlsx (ваши настоящие
430 объявлений со всеми их колонками — Id, AvitoId, AvitoStatus, Category,
ServiceType, Title, Description, Price, ImageUrls, Address и т.д.),
вносит в него только те точечные правки, которые вы явно указали в блоке
EDITS ниже, и сохраняет файл обратно — не трогая остальные строки и колонки.

Главное отличие от прошлой версии: скрипт ничего не "придумывает" и не
может случайно уменьшить число строк — есть проверка (см. safety check
в конце), которая ОСТАНАВЛИВАЕТ сохранение, если строк вдруг стало заметно
меньше, чем было. Это защита от повторения ситуации, когда файл случайно
перезаписался тестовыми данными.
"""

import sys
import pandas as pd

FEED_FILE = "BaronNeon_feed.xlsx"

# ============================================================
# EDITS — здесь описываете, что именно нужно поменять в этот раз.
# Ничего программировать не нужно — просто редактируете это место
# перед следующим запуском (или просите меня подготовить новую версию).
# ============================================================
EDITS = [
    {
        "column": "Price",
        "old_value": 760,
        "new_value": 750,
    },
    # Пример второй правки (раскомментируйте и заполните при необходимости):
    # {
    #     "column": "Title",
    #     "old_value": "Неоновая вывеска на заказ",
    #     "new_value": "Неоновая вывеска под заказ",
    # },
]

# Минимально ожидаемое число строк в файле. Если после чтения файла строк
# окажется меньше — что-то пошло не так (файл повреждён/подменён), скрипт
# аварийно остановится и НИЧЕГО не сохранит, чтобы не потерять данные.
MIN_EXPECTED_ROWS = 400


def main():
    df = pd.read_excel(FEED_FILE)
    original_rows = len(df)
    print(f"Прочитано строк: {original_rows}")

    if original_rows < MIN_EXPECTED_ROWS:
        print(
            f"СТОП: строк в файле ({original_rows}) меньше ожидаемого "
            f"минимума ({MIN_EXPECTED_ROWS}). Похоже, файл повреждён или "
            f"подменён тестовыми данными. Ничего не меняю и не сохраняю, "
            f"чтобы не потерять реальные объявления."
        )
        sys.exit(1)

    total_changed = 0
    for edit in EDITS:
        col = edit["column"]
        old_val = edit["old_value"]
        new_val = edit["new_value"]

        if col not in df.columns:
            print(f"Внимание: колонки '{col}' нет в файле, пропускаю правку.")
            continue

        mask = df[col] == old_val
        changed = mask.sum()
        df.loc[mask, col] = new_val
        total_changed += changed
        print(f"Колонка '{col}': заменено значений {old_val!r} -> {new_val!r} в {changed} строках.")

    # Safety check: после правок число строк должно остаться тем же самым —
    # мы никогда не удаляем и не добавляем строки, только меняем значения.
    if len(df) != original_rows:
        print("СТОП: число строк изменилось после правок — это не должно происходить. Файл не сохранён.")
        sys.exit(1)

    df.to_excel(FEED_FILE, index=False)
    print(f"Готово: {FEED_FILE} сохранён, строк: {len(df)}, изменено значений всего: {total_changed}")


if __name__ == "__main__":
    main()
